package com.ansh.atlaspractice.preset.impl;

import com.ansh.atlaspractice.kit.Kit;
import com.ansh.atlaspractice.preset.PresetKit;
import org.bukkit.Material;
import org.bukkit.inventory.ItemStack;
import org.bukkit.inventory.meta.ItemMeta;

public final class BattleRushPreset implements PresetKit {

    @Override
    public String getId() {
        return "BATTLERUSH";
    }

    @Override
    public String getDisplayName() {
        return "BattleRush";
    }

    @Override
    public ItemStack getDisplayIcon() {
        return new ItemStack(Material.WOOL);
    }

    @Override
    public void setup(Kit kit) {

        // â”€â”€ Armour â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
        ItemStack[] armor = new ItemStack[4];
        armor[0] = new ItemStack(Material.LEATHER_BOOTS);
        armor[1] = new ItemStack(Material.LEATHER_LEGGINGS);
        armor[2] = new ItemStack(Material.LEATHER_CHESTPLATE);
        armor[3] = new ItemStack(Material.LEATHER_HELMET);

        // â”€â”€ Inventory â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
        ItemStack[] contents = new ItemStack[36];

        // Slot 0 â€” 64 Wool
        contents[0] = new ItemStack(Material.WOOL, 64);

        // Slot 1 â€” Shears (unbreakable via DURABILITY flag on the kit itself)
        contents[1] = new ItemStack(Material.SHEARS, 1);

        // â”€â”€ Apply to kit â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
        kit.setArmorContents(armor);
        kit.setMainContents(contents);

        kit.setHungerLossEnabled(false);
        kit.setDurabilityEnabled(false);
        kit.setDamageEnabled(false);
    }
}
