package com.ansh.atlaspractice.replay;

import org.bukkit.command.Command;
import org.bukkit.command.CommandExecutor;
import org.bukkit.command.CommandSender;
import org.bukkit.entity.Player;

public final class ReplayViewCommand implements CommandExecutor {
    private final ReplayManager replayManager;

    public ReplayViewCommand(ReplayManager replayManager) {
        this.replayManager = replayManager;
    }

    @Override
    public boolean onCommand(CommandSender sender, Command command, String label, String[] args) {
        if (!(sender instanceof Player)) {
            sender.sendMessage("Only players can view replays.");
            return true;
        }
        if (args.length != 1) {
            sender.sendMessage("§cUsage: /" + label + " <replayId>");
            return true;
        }
        replayManager.playReplay((Player) sender, args[0]);
        return true;
    }
}
